"""Emit the front camera colour matrix header from the private 0A214000.dcc.

    gen-front-ccm.py <dcc> <set> <index> <output.h>
    gen-front-ccm.py <dcc> list            print the matrices (terminal only)

<set>   swarc  the ISP_SW_ARC block ("Final tuning 460"), first table
        hwqc   the ISP_HW_QC block ("Mid tuning 460"), first table
<index> mean   the average of the six matrices (rows still sum to 1)
        0..5   one matrix of the table

Runs from the build (front-tuning/Android.mk).  The output goes to the build
output directory and must never be committed: the numbers are Microsoft's
calibration of this module.  The DCC is pinned by the same SHA-256 as the
register generator (../vs6955/generate-vs6955.py).

Layout, from the pinned file (both blocks share it):

  "|ISP_HW_QC|"  then at 0x1228 the header 00 06 00 03 06 12 13 14,
                 six 3x3 matrices at 0x1230 (stride 36), an identical
                 second table at 0x1308
  "|ISP_SW_ARC|" then at 0xc2e2 the same header, six matrices at 0xc2ea,
                 a second table at 0xc3c2 whose entry 2 repeats entry 1

Each matrix is nine little-endian int32 in Q16, row-major, rows summing to
65536 (within 3).  Which illuminant each of the six belongs to is not known;
the chromatix receives ONE matrix in all eight of its entries, as the rear
tuning does, so color_correct40_interpolate() cannot blend in the IMX179's.
"""
import hashlib
import struct
import sys
from pathlib import Path

DCC_SHA256 = "16cc9406ad86f149115181596bd62fb0eb7231ede319df15bfe53575a26be10c"
HEADER = bytes.fromhex("0006000306121314")
SETS = {
    # name: (block label, header offset, second table offset)
    "hwqc":  (b"|ISP_HW_QC|",  0x1228, 0x1308),
    "swarc": (b"|ISP_SW_ARC|", 0xc2e2, 0xc3c2),
}
COUNT = 6
CHX_ENTRIES = 8          # ccm_0..ccm_7 in chx_vfe_t


def fail(msg):
    raise SystemExit("gen-front-ccm: " + msg)


def load(path):
    data = Path(path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != DCC_SHA256:
        fail("unexpected DCC %s (want %s)" % (digest, DCC_SHA256))
    return data


def table(data, name):
    label, hdr, second = SETS[name]
    at = data.find(label)
    if at < 0 or not 0 < hdr - at < 0x60:
        fail("%s: block label not found just before 0x%x" % (name, hdr))
    if data[hdr:hdr + 8] != HEADER:
        fail("%s: header at 0x%x is %s" % (name, hdr, data[hdr:hdr + 8].hex()))
    out = []
    for i in range(COUNT):
        q = struct.unpack_from("<9i", data, hdr + 8 + 36 * i)
        for r in range(3):
            if abs(sum(q[3 * r:3 * r + 3]) - 65536) > 3:
                fail("%s[%d]: row %d sums to %d" % (name, i, r, sum(q[3 * r:3 * r + 3])))
            if not 32768 < q[4 * r] < 262144:
                fail("%s[%d]: diagonal %d out of range" % (name, i, q[4 * r]))
        out.append(q)
    if name == "hwqc" and any(struct.unpack_from("<9i", data, second + 36 * i) != out[i]
                              for i in range(COUNT)):
        fail("hwqc: the second table at 0x%x no longer equals the first" % second)
    return out


def matrix(data, name, index):
    t = table(data, name)
    if index == "mean":
        return [sum(m[k] for m in t) / (COUNT * 65536.0) for k in range(9)]
    try:
        i = int(index)
    except ValueError:
        i = -1
    if not 0 <= i < COUNT:
        fail("index must be mean or 0..%d, got %r" % (COUNT - 1, index))
    return [v / 65536.0 for v in t[i]]


def f32(v):
    bits = struct.pack("<f", v)
    for prec in range(1, 10):
        t = "%.*g" % (prec, v)
        if struct.pack("<f", float(t)) == bits:
            break
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def emit(path, name, index, m):
    init = "{ " + ", ".join(f32(v) for v in m) + " }"
    text = [
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        "/* Private: derived from the Lumia calibration 0A214000.dcc, do not commit. */",
        "/* Input SHA-256: %s */" % DCC_SHA256,
        "/* Generated by gen-front-ccm.py: set %s, index %s. */" % (name, index),
        "#ifndef CITYMAN_FRONT_CCM_GENERATED_H",
        "#define CITYMAN_FRONT_CCM_GENERATED_H",
        "#define CITYMAN_FRONT_CCM_SET \"%s\"" % name,
        "#define CITYMAN_FRONT_CCM_INDEX \"%s\"" % index,
        "#define CITYMAN_FRONT_DCC_CCM %s" % init,
        "#endif",
        "",
    ]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text("\n".join(text))
    tmp.replace(path)


def main(argv):
    if len(argv) == 3 and argv[2] == "list":
        data = load(argv[1])
        for name in ("swarc", "hwqc"):
            for i, q in enumerate(table(data, name)):
                print("%-5s %d  %s" % (name, i, " ".join("%+.4f" % (v / 65536.0) for v in q)))
            print("%-5s mean %s" % (name, " ".join("%+.4f" % v for v in matrix(data, name, "mean"))))
        return 0
    if len(argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    dcc, name, index, out = argv[1:]
    name = {"sw_arc": "swarc", "hw_qc": "hwqc"}.get(name, name)
    if name not in SETS:
        fail("set must be swarc or hwqc, got %r" % name)
    emit(out, name, index, matrix(load(dcc), name, index))
    return 0


if __name__ == "__main__":
    sys.dont_write_bytecode = True
    sys.exit(main(sys.argv))
